/**
 * 一段话有没有东西可拿（2026-10-25 · §173）。
 *
 * 【为什么单独一份】同一个「空」判据在这条链上有两处要用：
 * ① 消息动作条——空正文不挂动作（挂一枚「复制」点下去必然失败）；
 * ② 写剪贴板——空文本不进剪贴板（写进去等于把上一条内容留在那儿，粘出来会拿到不相干的东西）。
 * 两处各判一次「空」就等于各写一遍；改了一处忘了另一处，空消息上就又会冒出一枚点不成的钮
 * ——那正是本轮真机复验捞出来的那个形状。⇒ 判据只有这一份。
 */

/** 有字（哪怕只有一个字）就成立；空串与纯空白都不成立。 */
export function hasMessageText(text: string): boolean {
  return text.trim() !== "";
}
