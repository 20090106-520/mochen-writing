- 不要一次给所有配角钉链。主线人物五六个人够了，钉多了没有一条会被真的对过。
- 不要把「不肯跨的线」写成口号（「他绝不会背叛朋友」）。口号不是线，
  拿它去对照一场戏，得不出任何结论。
- 不要用这条链去解释他所有的选择。链是用来**排除**的：照链排除掉不成立的动作，
  剩下的才需要理由。
