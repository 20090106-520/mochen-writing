- 不要每章都用同一种钩子。连着五章都用「门外来人」，读者会开始预判。
- 不要在章尾把话说满。「他决定去复仇」把话说尽了，接下来只能更狠；
  「他决定去复仇，但没告诉任何人」才有下一章。
