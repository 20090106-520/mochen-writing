- 不要因为「结构完整」就以为这一段写好了。结构完整和好看是两件事。
- 不要在同一段里套两个结构再对不上号。那不是复杂，是没想清楚。
- 不要在动笔前把对照表写完就不再看。它是**写完之后**才用来量东西的。
